import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { BrowserRouter } from 'react-router-dom'
import './index.css'
import App from './App.jsx'

// Reload when a new service worker takes control so users always get fresh content.
// vite-plugin-pwa's autoUpdate mode uses skipWaiting+clientsClaim but the generated
// registerSW.js doesn't include a controllerchange handler, so we add one here.
if ('serviceWorker' in navigator) {
  navigator.serviceWorker.addEventListener('controllerchange', () => {
    window.location.reload()
  })
}

createRoot(document.getElementById('root')).render(
  <StrictMode>
    <BrowserRouter>
      <App />
    </BrowserRouter>
  </StrictMode>,
)
